#!/usr/bin/env python3
"""Validate Git commit messages and PR bodies against attribution policy.

Rejects automated Cursor/AI marketing attribution while allowing legitimate
technical references to Cursor ACP product functionality.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Iterable, List, Optional, Sequence, Tuple


FORBIDDEN_LINE_PATTERNS: Tuple[re.Pattern[str], ...] = (
    re.compile(r"(?i)^\s*Co-authored-by:\s*Cursor(\s|<|$)"),
    re.compile(r"(?i)^\s*Co-authored-by:\s*Cursor\s+AI\b"),
    re.compile(r"(?i)^\s*Co-authored-by:\s*AI\b"),
    re.compile(r"(?i)^\s*Co-authored-by:\s*Claude\b"),
    re.compile(r"(?i)^\s*Made-with:\s*Cursor\b"),
    re.compile(r"(?i)^\s*Made with\s+Cursor\b"),
    re.compile(r"(?i)^\s*Made with\s+\[Cursor\]\(https?://cursor\.com/?\)\s*$"),
    re.compile(r"(?i)^\s*Generated by\s+Cursor\b"),
    re.compile(r"(?i)^\s*Generated with\s+AI\b"),
    re.compile(r"(?i)^\s*Assisted by\s+Cursor\b"),
)


def _strip_fenced_code(text: str) -> str:
    """Remove fenced code blocks so quoted examples do not fail validation."""
    return re.sub(r"```.*?```", "", text, flags=re.DOTALL)


def find_violations(text: str) -> List[str]:
    scanned = _strip_fenced_code(text)
    hits: List[str] = []
    for lineno, line in enumerate(scanned.splitlines(), start=1):
        for pat in FORBIDDEN_LINE_PATTERNS:
            if pat.search(line):
                hits.append(f"line {lineno}: {line.rstrip()}")
                break
    return hits


def validate_message(text: str, *, label: str) -> int:
    hits = find_violations(text)
    if not hits:
        print(f"PASS {label}: no forbidden attribution")
        return 0
    print(f"FAIL {label}: forbidden automated attribution detected", file=sys.stderr)
    for hit in hits:
        print(f"  {hit}", file=sys.stderr)
    return 1


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "commit_msg_file",
        nargs="?",
        help="Path to commit message file (Git commit-msg hook argument)",
    )
    parser.add_argument(
        "--pr-body-file",
        help="Validate a pull request description Markdown file",
    )
    parser.add_argument(
        "--text",
        help="Validate an inline message/body string",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    rc = 0
    if args.commit_msg_file:
        text = Path(args.commit_msg_file).read_text(encoding="utf-8")
        rc |= validate_message(text, label=f"commit-msg:{args.commit_msg_file}")
    if args.pr_body_file:
        text = Path(args.pr_body_file).read_text(encoding="utf-8")
        rc |= validate_message(text, label=f"pr-body:{args.pr_body_file}")
    if args.text is not None:
        rc |= validate_message(args.text, label="text")
    if not args.commit_msg_file and not args.pr_body_file and args.text is None:
        parser.error("provide commit_msg_file, --pr-body-file, and/or --text")
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
